def populate(db_path: Path):
    conn = sqlite3.connect(db_path)
    c    = conn.cursor()

    # ── dtc_extended ──────────────────────────────────────────────────────────
    c.execute("""
        CREATE TABLE IF NOT EXISTS dtc_extended (
            code                  TEXT NOT NULL,
            source                TEXT NOT NULL DEFAULT 'professional',
            symptoms              TEXT,
            technical_diagnosis   TEXT,
            real_solution         TEXT,
            probable_causes       TEXT,
            tools_needed          TEXT,
            estimated_time_hours  REAL,
            cost_min_usd          INTEGER,
            cost_max_usd          INTEGER,
            cost_labor_usd        INTEGER,
            PRIMARY KEY (code, source)
        )
    """)
    inserted_ext = 0
    for row in DTC_EXTENDED:
        code, symptoms, tech_diag, real_sol, prob_causes, tools, hours, cmin, cmax, clabor = row
        c.execute("""
            INSERT OR IGNORE INTO dtc_extended
            (code, source, symptoms, technical_diagnosis, real_solution,
             probable_causes, tools_needed, estimated_time_hours,
             cost_min_usd, cost_max_usd, cost_labor_usd)
            VALUES (?,?,?,?,?,?,?,?,?,?,?)
        """, (code, "professional", symptoms, tech_diag, real_sol,
              prob_causes, tools, hours, cmin, cmax, clabor))
        inserted_ext += c.rowcount

    # ── oem_desc ──────────────────────────────────────────────────────────────
    inserted_oem = 0
    for code, make, desc, hint in OEM_VARIANTS:
        c.execute("INSERT OR REPLACE INTO oem_desc (code, make, description, fix_hint) VALUES (?,?,?,?)",
                  (code, make, desc, hint))
        inserted_oem += c.rowcount

    # ── EV DTCs en dtc_codes ──────────────────────────────────────────────────
    inserted_ev = 0
    for code, desc, system, sev, source in EV_DTCS_FOR_DB:
        c.execute("""
            INSERT OR IGNORE INTO dtc_codes (code, description, system, severity, source)
            VALUES (?,?,?,?,?)
        """, (code, desc, system, sev, source))
        inserted_ev += c.rowcount

    conn.commit()
    conn.close()

    print(f"✓ dtc_extended: {inserted_ext} filas nuevas (de {len(DTC_EXTENDED)} en el script)")
    print(f"✓ oem_desc:     {inserted_oem} filas nuevas (de {len(OEM_VARIANTS)} en el script)")
    print(f"✓ dtc_codes EV: {inserted_ev} filas nuevas (de {len(EV_DTCS_FOR_DB)} en el script)")


if __name__ == "__main__":
    if not DB_PATH.exists():
        print(f"ERROR: DB no encontrada en {DB_PATH}")
        sys.exit(1)
    populate(DB_PATH)
    print(f"\nBase de datos actualizada: {DB_PATH}")
